"""LaTeX procedure and report (OUT-8), rendered from the JSON run record.

The output is a fragment, not a document: no ``\\documentclass`` and no packages,
so ``\\input{procedure.tex}`` drops it into any LaTeX document (pdfLaTeX, XeLaTeX
or LuaLaTeX). Steps are a plain ``enumerate`` that keeps stepdoc's numbers as the
item labels (``1.``, ``1.2.``, ``S1.``), code is ``\\texttt``, and every style is
a ``\\providecommand`` at the top (``\\stepdocTest``, ``\\stepdocCode``…), so a
document that defines one first changes how it looks.

A guarded check (pytest-verifier's ``guard``, CHK-12) is one item, ``Verify
'<name>', depending on the condition:``, with an ``itemize`` of its branches
(``If <condition>: Verify …``, ``Else if …``, ``Otherwise: …``). The procedure
lists every branch; the report sets the branch the run took in bold, with its
result, and greys the others out (italic without ``xcolor``).
"""

