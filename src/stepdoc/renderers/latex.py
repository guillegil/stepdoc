PREAMBLE = r"""% Generated by stepdoc. A LaTeX fragment: \input{} it into any document.
% Each style below is a \providecommand: define it before the \input to change it.
\makeatletter
\providecommand{\stepdocTitle}[1]{\section*{#1}}
\providecommand{\stepdocTest}[1]{\subsection*{#1}}
\providecommand{\stepdocSection}[1]{\par\medskip\noindent\textbf{#1}\par}
\providecommand{\stepdocCode}[1]{\texttt{#1}}
\providecommand{\stepdocMeta}[1]{\par\noindent\textit{#1}\par\smallskip}
\providecommand{\stepdocNote}[1]{\par\textit{#1}}
\providecommand{\stepdocTaken}[1]{\textbf{#1}}
\providecommand{\stepdocNotRun}[1]{\@ifundefined{textcolor}{\textit{#1}}{\textcolor{gray}{#1}}}
\providecommand{\stepdocPass}{\@ifundefined{checkmark}{\textsf{pass}}{\ensuremath{\checkmark}}}
\providecommand{\stepdocFail}{\ensuremath{\times}}
\providecommand{\stepdocUnknown}{?}
\providecommand{\stepdocNotJudged}{\ensuremath{\cdot}}
\makeatother
"""

# Characters LaTeX gives a meaning to, and ones that would join a neighbour into
# a ligature (``--`` is a dash, ``''`` a closing quote, ``<`` is ¡ in OT1).
_ESCAPES = {
    "\\": r"\textbackslash{}",
    "{": r"\{",
    "}": r"\}",
    "$": r"\$",
    "&": r"\&",
    "#": r"\#",
    "%": r"\%",
    "_": r"\_",
    "^": r"\textasciicircum{}",
    "~": r"\textasciitilde{}",
    "<": r"\textless{}",
    ">": r"\textgreater{}",
    "|": r"\textbar{}",
    "-": "{-}",
    "'": "{'}",
    "`": r"\textasciigrave{}",
    '"': r"\char34{}",  # a straight quote in typewriter fonts
    # Symbols pdfLaTeX cannot typeset from UTF-8 without extra packages.
    "∈": r"\ensuremath{\in}",
    "∉": r"\ensuremath{\notin}",
    "±": r"\ensuremath{\pm}",
    "≤": r"\ensuremath{\le}",
    "≥": r"\ensuremath{\ge}",
    "≠": r"\ensuremath{\ne}",
    "×": r"\ensuremath{\times}",
    "→": r"\ensuremath{\rightarrow}",
    "…": r"\dots{}",
    "—": r"\textemdash{}",
    "–": r"\textendash{}",
    "·": r"\textperiodcentered{}",
    "✓": r"\stepdocPass{}",
    "✗": r"\stepdocFail{}",
    "\n": " ",
    "\t": " ",
}
_TABLE = str.maketrans(_ESCAPES)
# In code (a typewriter font), these characters by their slot, which every font
# encoding gives them there: OT1's \textless is a math glyph without a typewriter shape.
_CODE = str.maketrans(
    {**_ESCAPES, "'": r"\textquotesingle{}", **{c: rf"\char{ord(c)}{{}}" for c in "\\{}<>|~^"}}
)

_MARKS = {"✓": r"\stepdocPass", "✗": r"\stepdocFail", "?": r"\stepdocUnknown", "·": r"\stepdocNotJudged", "–": r"\textendash"}

# LaTeX allows four nested enumerates and six nested lists in all. Deeper entries
# join the deepest list (their numbers still show where they belong).
_MAX_ENUM = 4
_MAX_LISTS = 6


def escape(text: str) -> str:
    """Text as LaTeX that prints it as it is."""
    return text.translate(_TABLE)


def _code(text: str) -> str:
    return r"\stepdocCode{" + text.translate(_CODE) + "}" if text else ""


def _words(text: str) -> str:
    """Prose whose `code` spans (FMT-1) are set as code."""
    return "".join(_code(t) if code else escape(t) for t, code in spans(" ".join(text.split())))


def _name(text: str) -> str:
    """A check's name in quotes (``'Speed':``) with typographic quotes."""
    return "`" + escape(text[1:]) if text.startswith("'") else escape(text)


def _label(number: Optional[str]) -> str:
    return "[" + (escape(number) + "." if number else r"\textendash") + "]"


def _mark(mark: Optional[str]) -> str:
    return _MARKS.get(mark or "", escape(mark or ""))


# --------------------------------------------------------------------------- #
# Lines
# --------------------------------------------------------------------------- #


def _line_text(line: Line, report: bool) -> str:
    """A line's words without its number: the step title in bold, or the verb, the
    check's name and its code; in the report also its result, mark and note."""
    if line.is_step:
        parts = [r"\textbf{" + _words(line.code) + "}"]
    else:
        label = _name(line.label) if line.label else ""
        parts = [" ".join(p for p in (escape(line.verb), label, _code(line.code)) if p)]
        if line.aside:
            parts.append(f"({escape(' '.join(line.aside.split()))})")
        if line.result:
            parts.append(r"\ensuremath{\rightarrow} " + _code(line.result))
    if report and line.mark:
        parts.append(_mark(line.mark))
    if line.note and (report or line.is_step):
        parts.append(r"\textit{" + escape(line.note) + "}")
    text = " ".join(parts)
    if line.remark:
        text += "".join(r"\stepdocNote{" + escape(r) + "}" for r in line.remark.splitlines() if r.strip())
    return text


class _Writer:
    """Nested lists from the record's tree of entries."""

    def __init__(self, report: bool, known: Optional[dict[str, list[Optional[Record]]]] = None) -> None:
        self.report = report
        self.symbolic = not report
        self.known = known or {}
        self.out: list[str] = []
        self.enums = 0
        self.lists = 0

    def emit(self, text: str) -> None:
        self.out.append("  " * self.lists + text)

    def items(self, entries: list[Record]) -> None:
        """``entries`` as an enumerate, or as items of the list already open when
        LaTeX allows no deeper one."""
        if not entries:
            return
        nest = self.enums < _MAX_ENUM and self.lists < _MAX_LISTS
        if nest:
            self.emit(r"\begin{enumerate}")
            self.enums += 1
            self.lists += 1
        for e in entries:
            self.entry(e)
        if nest:
            self.enums -= 1
            self.lists -= 1
            self.emit(r"\end{enumerate}")

    def entry(self, e: Record) -> None:
        kind = e["type"]
        if kind == "step":
            self.item(next(step_lines(e, self.symbolic)))
            self.items(e["entries"])
        elif kind == "repeat":
            self.item(repeat_line(e, self.symbolic, 0))
            self.items(e["entries"])
        elif kind == "check":
            self.check(e)
        else:
            self.item(action_line(e, self.symbolic, 0))

    def item(self, line: Line, text: Optional[str] = None) -> None:
        self.emit(r"\item" + _label(line.number) + " " + (text if text is not None else _line_text(line, self.report)))

    def check(self, c: Record) -> None:
        if c.get("branches"):
            self.guard(c)
            return
        self.item(check_line(c, self.symbolic, 0))
        if self.symbolic and c.get("each"):
            return  # CHK-11: the failed items belong to this run, not the procedure
        self.items(c.get("children") or [])

    # ----------------------------------------------------------------------- #
    # Guarded checks (CHK-12)
    # ----------------------------------------------------------------------- #

    def guard(self, c: Record) -> None:
        line = check_line(c, self.symbolic, 0)
        name = c.get("label")
        head = "Verify " + (_name(f"'{name}', ") if name else "") + "depending on the condition:"
        if self.report:
            head += " " + _mark(line.mark)
            if c["passed"] is False and not any(b["taken"] for b in c["branches"]) and c.get("detail"):
                head += r" \textit{" + escape(c["detail"]) + "}"
        self.item(line, head)
        self.branches(c)

    def branches(self, c: Record) -> None:
        """One item per branch: every branch in the procedure; in the report the
        branch the run took in bold, with its result, the others greyed out."""
        nest = self.lists < _MAX_LISTS
        if nest:
            self.emit(r"\begin{itemize}")
            self.lists += 1
        known = self.known.get(_guard_key(c), [])
        seen_taken = False
        for i, b in enumerate(c["branches"]):
            check = b.get("check")
            generic = check is None and i < len(known) and known[i] is not None
            if generic:
                check = known[i]  # another case built this branch's check: its generic text
            words = _opening(b, i) + " " + self._branch_check(b, check, generic)
            if not self.report:
                self.emit(r"\item " + words)
            elif b["taken"]:
                seen_taken = True
                tail = ""
                if check is not None and not check.get("branches"):
                    result = check_line(check, False, 0)
                    tail = " " + _mark(result.mark)
                    if result.result:
                        tail = r" \ensuremath{\rightarrow} " + _code(result.result) + tail
                self.emit(r"\item \stepdocTaken{" + words + "}" + tail)
            else:
                why = "condition false" if b.get("holds") is False and not seen_taken else "not evaluated"
                self.emit(r"\item \stepdocNotRun{" + words + f" ({why})" + "}")
            if check is not None and check.get("branches"):
                self.branches(check)  # a guard in a branch: its own branches under it
        if nest:
            self.lists -= 1
            self.emit(r"\end{itemize}")

    def _branch_check(self, b: Record, check: Optional[Record], generic: bool = False) -> str:
        if check is not None:
            if check.get("branches"):
                name = check.get("label")
                return "Verify " + (_name(f"'{name}', ") if name else "") + "depending on the condition:"
            line = check_line(check, self.symbolic or generic, 0)
            label = _name(line.label) if line.label else ""
            text = " ".join(p for p in ("Verify", label, _code(line.code)) if p)
            if line.aside:
                text += f" ({escape(' '.join(line.aside.split()))})"
            return text
        if b.get("wording"):
            return self._branch_check(b, b["wording"], True)
        if b.get("source"):
            return "Verify " + _code(b["source"])
        return r"\textit{a check made only when this branch is taken}"


def _opening(b: Record, index: int) -> str:
    """``If <condition> (<label>):``, ``Else if …``, ``Otherwise:``."""
    if b.get("default"):
        return "Otherwise:"
    word = "If" if index == 0 else "Else if"
    cond, label = b.get("condition"), b.get("label")
    if cond:
        return f"{word} {_code(cond)}" + (f" ({escape(label)})" if label else "") + ":"
    return f"{word} {escape(label) if label else f'branch {index + 1}'}:"


def _guard_key(c: Record) -> str:
    return json.dumps([c.get("location"), c.get("label"), c.get("text")], sort_keys=True)


def _guards(entries: list[Record]) -> Iterator[Record]:
    for e in entries:
        if e["type"] in ("step", "repeat"):
            yield from _guards(e["entries"])
        elif e["type"] == "check":
            if e.get("branches"):
                yield e
                yield from _guards([b["check"] for b in e["branches"] if b.get("check")])
            yield from _guards(e.get("children") or [])


def _known_branches(cases: list[Record]) -> dict[str, list[Optional[Record]]]:
    """For each guard of a procedure, the check of each branch from whichever case
    built it: a lazy check is built only in the cases that took its branch, and
    the procedure lists them all."""
    known: dict[str, list[Optional[Record]]] = {}
    for case in cases:
        for g in _guards(case["steps"] + case["unscoped"]):
            slots = known.setdefault(_guard_key(g), [None] * len(g["branches"]))
            for i, b in enumerate(g["branches"][: len(slots)]):
                if slots[i] is None and b.get("check") is not None:
                    slots[i] = b["check"]
    return known


def _without_choices(record: Record) -> Record:
    """The record without the branch each run took, so cases that took different
    branches of a guard share one procedure."""
    record = copy.deepcopy(record)
    for case in record["tests"]:
        for g in _guards(case["steps"] + case["unscoped"]):
            g["selected"] = None
    return record


