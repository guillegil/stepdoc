def _sections(w: _Writer, test: Record, sections: tuple[str, ...]) -> None:
    """A test's sections: pre-conditions, setup and teardown get a heading, the
    procedure gets one when the test has another section to tell it apart."""
    framed = any(has_section(test, s) for s in SECTIONS if s != "procedure")
    for section in sections:
        steps = [s for s in test["steps"] if s.get("section", "procedure") == section]
        loose = [e for e in test["unscoped"] if e.get("section", "procedure") == section]
        if not steps and not loose:
            continue
        if section != "procedure" or (framed and len(sections) > 1):
            w.out.append(r"\stepdocSection{" + SECTION_TITLE[section] + "}")
        if loose and section == "procedure":
            w.out.append(r"\stepdocSection{Unscoped}")
        w.items(loose + steps)


def _block(block: Block) -> list[str]:
    if block.kind == "p":
        return [_words(block.items[0]), ""]
    if block.kind == "ul":
        return [r"\begin{itemize}", *(r"  \item " + _words(i) for i in block.items), r"\end{itemize}", ""]
    rows = (rf"  \item[{n}.] " + _words(i) for n, i in zip(block.numbers, block.items))
    return [r"\begin{enumerate}", *rows, r"\end{enumerate}", ""]


def _doc(doc: Optional[dict[str, str]]) -> list[str]:
    """DOC-1: description, objective and acceptance criteria."""
    if not doc:
        return []
    out: list[str] = []
    for block in doc_blocks(doc.get("description", "")):
        out += _block(block)
    for key in ("objective", "acceptance"):
        if not doc.get(key):
            continue
        blocks = doc_blocks(doc[key])
        if key == "objective" and len(blocks) == 1 and blocks[0].kind == "p":
            out += [rf"\textbf{{{DOC_TITLE[key]}.}} " + _words(blocks[0].items[0]), ""]
            continue
        out += [rf"\noindent\textbf{{{DOC_TITLE[key]}}}", ""]
        for block in blocks:
            out += _block(block)
    return out


def _parameters(proc: Procedure) -> list[str]:
    rows = proc.param_table
    if not rows:
        return []
    described = any(d for _, d, _ in rows)
    title = "Parameters" + (f" (strategy {_code(proc.strategy)})" if proc.strategy else "")
    head = r"\textbf{Parameter} & " + (r"\textbf{Description} & " if described else "") + r"\textbf{Values} \\"
    out = [r"\stepdocSection{" + title + "}", r"\noindent\begin{tabular}{@{}l" + ("l" if described else "") + "l@{}}", head]
    for name, description, values in rows:
        cells = [_code(name)] + ([escape(description or "")] if described else []) + [", ".join(_code(v) for v in values)]
        out.append(" & ".join(cells) + r" \\")
    return out + [r"\end{tabular}", ""]


def render_procedure(record: Record, title: str = "Test procedures") -> str:
    """The generic procedure of every test: one per test, whatever cases it ran."""
    out = [PREAMBLE, r"\stepdocTitle{" + escape(title) + "}", ""]
    for proc in procedures(_without_choices(record)):
        n = len(proc.cases)
        out += [
            r"\stepdocTest{" + escape(short_name(proc.procedure_id)) + "}",
            r"\stepdocMeta{" + _code(proc.procedure_id) + f" \\textperiodcentered{{}} {n} case{'s' * (n != 1)}" + "}",
            "",
        ]
        out += _doc(procedure_doc(proc))
        out += _parameters(proc)
        w = _Writer(report=False, known=_known_branches(proc.cases))
        if proc.precondition is not None:
            _sections(w, proc.precondition, ("precondition",))
        if proc.setup is not None:
            _sections(w, proc.setup, ("setup",))
        for _, members in proc.variants:
            if len(proc.variants) > 1:
                cases = ", ".join(_code(m["case"] or m["id"]) for m in members)
                w.out.append(r"\stepdocSection{Procedure for " + cases + "}")
            elif proc.framed:
                w.out.append(r"\stepdocSection{Procedure}")
            longest = max(members, key=lambda m: len(test_lines(m, symbolic=True, sections=("procedure",))))
            _sections(w, longest, ("procedure",))
        if proc.teardown is not None:
            _sections(w, proc.teardown, ("teardown",))
        out += w.out + [""]
    return "\n".join(out).rstrip() + "\n"


def render_report(record: Record, title: str = "Test report") -> str:
    """What each case did: every step and check with its result."""
    out = [PREAMBLE, r"\stepdocTitle{" + escape(title) + "}", ""]
    if record.get("dry_run"):
        out += [r"\textit{Dry run: results were not judged.}", ""]
    known = {p.procedure_id: _known_branches(p.cases) for p in procedures(record)}
    for t in record["tests"]:
        verdict = "DRY RUN" if t["dry_run"] else OUTCOME_TEXT.get(t["outcome"], "?")
        out.append(r"\stepdocTest{" + escape(short_name(t["id"])) + r" \textemdash{} " + verdict + "}")
        meta = [_code(t["id"]), escape(t["started_at"])]
        if t["duration"] is not None:
            meta.append(f"{t['duration'] * 1000:.0f} ms")
        if t["seed"] is not None:
            meta.append("seed " + escape(show(t["seed"])))
        out += [r"\stepdocMeta{" + r" \textperiodcentered{} ".join(meta) + "}", ""]
        out += _doc(case_doc(t))
        if t["params"]:
            note = vector_note(t)
            line = r"\noindent Parameters: " + ", ".join(_code(f"{k} = {show(v)}") for k, v in t["params"].items())
            out += [line + (f" ({escape(note)})" if note else ""), ""]
        w = _Writer(report=True, known=known.get(t["procedure_id"]))
        _sections(w, t, SECTIONS)
        out += w.out + [""]
    return "\n".join(out).rstrip() + "\n"


